"""R-F independent-data scoring on the held receive path (2026-10-24): payload-exact frames, taps retrained on
random data, and equalise-first acquisition. Companion of heldpath_eq.py; see radio_firmware/reviews.md "Review of R-F".

usage: python heldpath_rf_score.py <rf dir> [train clip name]
  <rf dir> holds Grok's R-F clips m17_d<dev>_v<vga>_<n>.wav (DIAG rxclip, 8 kHz, bypass held) and taps.json
  (the +-20-symbol taps fitted on the R-E loop; index 0 = k=+20 ... index 40 = k=-20). The transmissions were
  generated by the R-F bench script: 1.6 s +-3 lead, preamble, LSF, 80 stream frames with random payloads from
  numpy's default_rng(10007 + 17 * sum(ord(c) for c in name)), callsign pair PAIRS[sum(ord) % 18], EOT.

Three passes over every clip:
  A. sync on the unequalised signal (m17.find_frames, 0.85), the taps applied per frame, payload-exact count;
  B. the same with taps retrained on <train clip name> (default m17_d2400_v20_0) -- shows the taps are not the loop;
  C. equalise first (taps at every sample phase, spacing one symbol), sync threshold 0.95, payload-exact count.
Result on the 2026-10-24 clips: A locks 12 of 18 and decodes 100 % of their frames; C locks all 18 with LSF CRC,
95 % payload-exact at -99 dBm and 98-100 % at -87/-93 dBm.
"""
import sys, json
from pathlib import Path
import numpy as np
import m17

RF = Path(sys.argv[1]); TRAIN = sys.argv[2] if len(sys.argv) > 2 else "m17_d2400_v20_0"
FS = 8000.0; L = 20; SIGN = -1.0; NFRAMES = 80
PAIRS = [("W1RF", "N2EQ"), ("K3M17", "W4LAB"), ("N5TST", "K6DEC"), ("W7RF", "N8EQ"), ("K9M17", "W2LAB"), ("N3TST", "K4DEC"),
         ("W5RF", "N6EQ"), ("K7M17", "W8LAB"), ("N9TST", "K2DEC"), ("W3RF", "N4EQ"), ("K5M17", "W6LAB"), ("N7TST", "K8DEC"),
         ("W9RF", "N1EQ"), ("K1M17", "W3LAB"), ("N4TST", "K5DEC"), ("W2RF", "N3EQ"), ("K6M17", "W9LAB"), ("N8TST", "K3DEC")]
LV = np.array([-3, -1, 1, 3], float)

def sent(name):
    rng = np.random.default_rng(10007 + sum(ord(c) for c in name) * 17)
    src, dst = PAIRS[sum(ord(c) for c in name) % len(PAIRS)]
    payloads = [bytes(int(v) for v in row) for row in rng.integers(0, 256, size=(NFRAMES, 16))]
    lsf = m17.lsf_bytes(src, dst)
    known = [np.array(list(m17.encode_lsf(lsf)), float)] + [
        np.array(list(m17.encode_stream(lsf, i | (0x8000 if i == NFRAMES - 1 else 0), payloads[i], i % 6)), float)
        for i in range(NFRAMES)]
    want = {i | (0x8000 if i == NFRAMES - 1 else 0): p for i, p in enumerate(payloads)}
    return known, want

def pcm(p):
    blob = p.read_bytes(); i = blob.find(b"data"); n = int.from_bytes(blob[i + 4:i + 8], "little")
    return np.frombuffer(blob[i + 8:i + 8 + n], dtype="<i2").astype(np.float64)

def loud(x):
    w = 400; r = np.array([np.sqrt(np.mean((x[i:i + w] - x[i:i + w].mean()) ** 2)) for i in range(0, x.size - w, 80)])
    on = np.flatnonzero(r > 800); i0 = on[0] * 80 + int(0.25 * FS) if on.size else 0
    x = x[i0:]; return x - x.mean()

def demod(name): return m17.demod(SIGN * loud(pcm(RF / (name + ".wav"))), FS)

def frames_raw(y, sps):
    out = []
    for start, kind, score, j in m17.find_frames(y, sps, thresh=0.85):
        lo = j - L * sps
        if lo < 0 or j + (192 + L) * sps > y.size: continue
        out.append((y[lo:j + (192 + L) * sps:sps], kind))
    return out

def eq_frame(seg, kind, w):
    sync = m17.SYNC_SYMS[kind]
    g, off = np.linalg.lstsq(np.vstack([sync, np.ones(8)]).T, seg[L:L + 8], rcond=None)[0]
    z = (seg - off) / g
    return np.array([np.dot(w, z[i:i + 2 * L + 1][::-1]) for i in range(192)])

def score_raw(name, w):
    known, want = sent(name); y, sps = demod(name)
    crc = ns = exact = g0 = 0
    for seg, kind in frames_raw(y, sps):
        eq = eq_frame(seg, kind, w)
        if kind == 'lsf': crc += m17.decode_lsf(eq[8:])[1]
        else:
            fn, p, lich, lerr = m17.decode_stream(eq[8:]); ns += 1; g0 += (lerr == 0); exact += (want.get(int(fn)) == p)
    return "LSF CRC %d  stream %2d  golay0 %2d  payload-exact %2d" % (crc, ns, g0, exact)

def train(name):
    known, want = sent(name); y, sps = demod(name); rows, tgt = [], []
    for seg, kind in frames_raw(y, sps):
        core = seg[L:L + 192]; cands = known if kind == 'lsf' else known[1:]
        c = [np.dot(core, k) / (np.linalg.norm(core) * np.linalg.norm(k)) for k in cands]
        if max(c) < 0.5: continue
        k = cands[int(np.argmax(c))]
        g, off = np.linalg.lstsq(np.vstack([k, np.ones(192)]).T, core, rcond=None)[0]
        z = (seg - off) / g
        for n in range(192): rows.append(z[n:n + 2 * L + 1][::-1]); tgt.append(k[n])
    return np.linalg.lstsq(np.array(rows), np.array(tgt), rcond=None)[0], len(tgt) // 192

def equalise_first(y, sps, w):
    """y_eq[n] = sum_i w[i] * y[n + (L - i) * sps]: the per-frame filter applied at every sample phase."""
    ye = np.zeros_like(y)
    for i, t in enumerate(w):
        sh = (L - i) * sps
        if sh >= 0: ye[:y.size - sh] += t * y[sh:]
        else: ye[-sh:] += t * y[:y.size + sh]
    return ye

def score_eqfirst(name, w, thresh=0.95):
    known, want = sent(name); y, sps = demod(name); ye = equalise_first(y, sps, w)
    crc = ns = exact = 0; first = None
    for start, kind, score, j in m17.find_frames(ye, sps, thresh=thresh):
        sy = ye[j:j + 8 * sps:sps]
        g, off = np.linalg.lstsq(np.vstack([m17.SYNC_SYMS[kind], np.ones(8)]).T, sy, rcond=None)[0]
        pay = (ye[start:start + 184 * sps:sps] - off) / g
        if pay.size < 184: break
        if first is None: first = score
        if kind == 'lsf': crc += m17.decode_lsf(pay)[1]
        else:
            fn, p, lich, lerr = m17.decode_stream(pay); ns += 1; exact += (want.get(int(fn)) == p)
    return "first sync %.3f  LSF CRC %d  stream %2d  payload-exact %2d" % (first or 0, crc, ns, exact)

taps = np.array(json.loads((RF / "taps.json").read_text())["taps"], float)
names = sorted(p.stem for p in RF.glob("m17_d*_v*_*.wav"))
print("== A. R-E loop taps, sync on the unequalised signal, payload-exact scoring")
for n in names: print("  %-18s %s" % (n, score_raw(n, taps)))
w, nf = train(TRAIN)
print("== B. taps retrained on %s (%d frames of random data)" % (TRAIN, nf))
print("taps:", " ".join("%+.3f" % v for v in w[::-1]))
for n in names: print("  %-18s %s" % (n, score_raw(n, w)))
print("== C. equalise first (R-E loop taps), sync threshold 0.95")
for n in names: print("  %-18s %s" % (n, score_eqfirst(n, taps)))
